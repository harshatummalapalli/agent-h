-- This is the flattened, literal record of what was applied directly to the
-- live Supabase project (fbkdypullttetardrgdu / "Agent H"), in this exact
-- order, via Supabase's migration tooling. It matches what
-- `npx supabase db diff --local -f agent_h_stage1_foundational_schema`
-- would generate from supabase/schemas/01 through 14 -- those files are the
-- fully commented, human-readable source of truth; this file is the
-- machine-applied record, per Atomic CRM's own migrations convention (see
-- doc/src/content/docs/developers/migrations.mdx).
--
-- 05_policies.sql is deliberately absent: Atomic CRM's original version
-- granted every authenticated user full read/write on everything, with no
-- isolation at all. Rather than apply that and immediately replace it, this
-- migration goes straight from the base schema to Agent H's tenant-scoped
-- policies (last section below).

