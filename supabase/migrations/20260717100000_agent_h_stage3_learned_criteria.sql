create index role_brief_learned_criteria_deal_id_idx on public.role_brief_learned_criteria using btree (deal_id);
create index role_brief_learned_criteria_tenant_id_idx on public.role_brief_learned_criteria using btree (tenant_id);
create index role_brief_learned_criteria_status_idx on public.role_brief_learned_criteria using btree (status);

create or replace trigger set_role_brief_learned_criteria_tenant_context_trigger
    before insert on public.role_brief_learned_criteria
    for each row execute function public.set_tenant_context_default();

create or replace trigger set_role_brief_learned_criteria_updated_at_trigger
    before update on public.role_brief_learned_criteria
    for each row execute function public.set_updated_at();

-- RLS: same tenant-scoped pattern as candidate_calibration_feedback, but
-- WITH an update policy this time -- unlike a calibration judgment (which
-- is immutable once made), a learned criterion's status is meant to be
-- toggled (Relax / Reapply) after creation.
alter table public.role_brief_learned_criteria enable row level security;

create policy "Learned criteria read within tenant" on public.role_brief_learned_criteria for select to authenticated
    using (tenant_id = public.current_tenant_id());
create policy "Learned criteria insert within tenant" on public.role_brief_learned_criteria for insert to authenticated
    with check (tenant_id = public.current_tenant_id());
create policy "Learned criteria status update within tenant" on public.role_brief_learned_criteria for update to authenticated
    using (tenant_id = public.current_tenant_id())
    with check (tenant_id = public.current_tenant_id());
