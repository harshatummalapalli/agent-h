--
-- Agent H Stage 1: tenant foundation
-- Every tenant-scoped table gets tenant_id + org_type. org_type is kept in
-- sync with tenants.org_type via a trigger (set_tenant_context_default) so
-- it can never drift out of sync with the tenant it belongs to.
--

create table public.tenants (
    id bigint generated by default as identity primary key,
    name text not null,
    org_type text not null check (org_type in ('staffing', 'in_house')),
    created_at timestamp with time zone not null default now()
);

comment on table public.tenants is 'A recruiting organization using Agent H: either a staffing firm (e.g. TalentCursor) or an in-house recruiting team at a company. org_type drives which mode of the product a tenant sees.';

-- Seed tenant: staffing mode (TalentCursor) is built first per Stage 1 resolution.
insert into public.tenants (name, org_type) values ('TalentCursor', 'staffing');

-- Resolves the tenant of the currently authenticated user, via their sales row.
create or replace function public.current_tenant_id() returns bigint
    language plpgsql security definer
    set search_path to ''
    as $$
begin
  return (select tenant_id from public.sales where user_id = auth.uid());
end;
$$;

comment on function public.current_tenant_id() is 'Returns the tenant_id of the logged-in recruiter. Used throughout RLS policies for tenant isolation.';

-- Generic before-insert trigger: auto-fills tenant_id from the inserting
-- user's own sales row (mirrors the existing set_sales_id_default pattern),
-- then copies org_type from the resolved tenant so the two can never disagree.
-- Not attached to public.sales itself -- that table's tenant assignment
-- happens at signup time, inside handle_new_user().
create or replace function public.set_tenant_context_default() returns trigger
    language plpgsql security definer
    set search_path to ''
    as $$
declare
  resolved_tenant_id bigint;
begin
  if new.tenant_id is null then
    select tenant_id into resolved_tenant_id from public.sales where user_id = auth.uid();
    new.tenant_id := resolved_tenant_id;
  end if;

  if new.tenant_id is not null then
    select org_type into new.org_type from public.tenants where id = new.tenant_id;
  end if;

  return new;
end;
$$;

comment on function public.set_tenant_context_default() is 'Auto-populates tenant_id (from the current user) and org_type (copied from that tenant) on insert, for every tenant-scoped table.';

