-- Update the auth-signup trigger function to resolve and stamp tenant_id/org_type
-- onto the new sales row (bootstraps to the first tenant if none specified --
-- fine while there's only one tenant; a real invite/tenant-picker flow is
-- later-stage product work, not schema).
CREATE OR REPLACE FUNCTION "public"."handle_new_user"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  sales_count int;
  target_tenant_id bigint;
  target_org_type text;
begin
  select count(id) into sales_count
  from public.sales;

  target_tenant_id := nullif(new.raw_user_meta_data ->> 'tenant_id', '')::bigint;

  if target_tenant_id is null then
    select id into target_tenant_id from public.tenants order by id limit 1;
  end if;

  select org_type into target_org_type from public.tenants where id = target_tenant_id;

  insert into public.sales (first_name, last_name, email, user_id, administrator, tenant_id, org_type)
  values (
    coalesce(new.raw_user_meta_data ->> 'first_name', new.raw_user_meta_data -> 'custom_claims' ->> 'first_name', 'Pending'),
    coalesce(new.raw_user_meta_data ->> 'last_name', new.raw_user_meta_data -> 'custom_claims' ->> 'last_name', 'Pending'),
    new.email,
    new.id,
    case when sales_count > 0 then FALSE else TRUE end,
    target_tenant_id,
    target_org_type
  );
  return new;
end;
$$;
